def test_structural_digest_shape_and_normalized_hash() -> None:
    skill_md = (
        "---\nname: demo\ndescription: \"x\"\n---\n\n"
        "# Demo\n\n## Identity\n\nbody\n\n## Guardrails\n\nrules\n\n"
        "---\n*Generated by AgentForge | Source: Unknown | 2026-08-03*\n"
    )
    identity_yaml = "schema_version: '1.0'\nrole:\n  title: Demo\n"
    d1 = structural_digest(skill_md, identity_yaml, "demo", ["instructions/voice.md"])
    assert d1["skill_name"] == "demo"
    assert d1["frontmatter_keys"] == ["description", "name"]
    assert d1["frontmatter_name"] == "demo"
    assert d1["h2_headings"] == ["Guardrails", "Identity"]
    assert d1["supplementary_paths"] == ["instructions/voice.md"]
    assert d1["identity_keys"] == ["role", "schema_version"]
    assert d1["num_h2"] == 2
    assert d1["num_supplementary"] == 1
    assert len(d1["normalized_body_sha256"]) == 64

    # Date / Generated-by footer must not affect hash
    skill_md_other_date = skill_md.replace("2026-08-03", "2099-01-01")
    d2 = structural_digest(skill_md_other_date, identity_yaml, "demo", ["instructions/voice.md"])
    assert d1["normalized_body_sha256"] == d2["normalized_body_sha256"]
    assert "*Generated by*" not in normalize_skill_md_for_hash(skill_md)
    assert "2026-08-03" not in normalize_skill_md_for_hash(skill_md)


def test_digest_match_against_shipped_lock(methodology: MethodologyExtraction | None) -> None:
    path = FIXTURE_DIR / "senior_data_engineer_extraction.json"
    digest_path = digest_path_for_fixture(path)
    assert digest_path.is_file()
    expected = json.loads(digest_path.read_text(encoding="utf-8"))

    result = evaluate_fixture_file(
        path,
        methodology_path=METH_PATH if methodology else None,
        apply_audit_fix=True,
    )
    assert result.digest_ok is True
    assert result.digest == expected
    assert compare_digests(result.digest or {}, expected) == []


def test_digest_intentional_mismatch_fails(
    methodology: MethodologyExtraction | None, tmp_path: Path
) -> None:
    path = FIXTURE_DIR / "platform_sre_extraction.json"
    # First get a real digest, then corrupt expected fields
    good = evaluate_fixture_file(
        path,
        methodology_path=METH_PATH if methodology else None,
        apply_audit_fix=True,
        digest_path=tmp_path / "missing.digest.json",  # no compare
    )
    assert good.digest is not None
    assert good.digest_ok is True

    corrupted = dict(good.digest)
    corrupted["skill_name"] = "wrong-slug"
    corrupted["h2_headings"] = ["Totally", "Different"]
    corrupted["normalized_body_sha256"] = "0" * 64

    bad_path = tmp_path / "platform_sre.digest.json"
    bad_path.write_text(json.dumps(corrupted), encoding="utf-8")

    result = evaluate_fixture_file(
        path,
        methodology_path=METH_PATH if methodology else None,
        apply_audit_fix=True,
        digest_path=bad_path,
    )
    assert result.digest_ok is False
    assert "skill_name" in result.digest_detail
    assert "h2_headings" in result.digest_detail
    assert "normalized_body_sha256" in result.digest_detail
    assert any("structural digest mismatch" in e for e in result.errors)
    assert result.passed is False


